const hash = (s) => [...String(s)].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) >>> 0, 7);

// Same quote all day (e.g. on the Now screen), different each day.
export function quoteOfDay(day) {
  return QUOTES[hash(day) % QUOTES.length];
}

export function randomQuote(rand = Math.random) {
  return QUOTES[Math.floor(rand() * QUOTES.length) % QUOTES.length];
}

export const formatQuote = ([text, author]) => `“${text}” (${author})`;
